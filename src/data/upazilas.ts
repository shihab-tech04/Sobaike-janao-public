/**
 * Returns all upazilas/thanas for a given district ID.
 */
export function getUpazilasByDistrict(districtId: string): UpazilaInfo[] {
  if (!districtId) return [];
  const normalized = districtId.trim().toLowerCase();
  return BANGLADESH_UPAZILAS.filter((u) => u.districtId.toLowerCase() === normalized);
}

